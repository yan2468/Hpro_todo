const BY_YEAR: Record<number, YearHolidays> = {
  2025: HOLIDAYS_2025,
  2026: HOLIDAYS_2026,
};

function key(d: Date): string {
  const p = (n: number) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
}

/** 判断某一天是否为工作日（法定节假日放假、调休补班上班） */
export function isWorkingDay(d: Date = new Date()): boolean {
  const k = key(d);
  const y = BY_YEAR[d.getFullYear()];
  if (y) {
    if (y.rest.includes(k)) return false; // 法定节假日放假
    if (y.work.includes(k)) return true; // 调休补班：周末也上班
  }
  // 无特殊安排时：周末非工作日，其余为工作日
  const day = d.getDay();
  return day !== 0 && day !== 6;
}

/** 是否为法定节假日（放假当天，含调休补休） */
export function isHoliday(d: Date = new Date()): boolean {
  const y = BY_YEAR[d.getFullYear()];
  return !!y && y.rest.includes(key(d));
}
